namespace MarkMello.Domain;

/// <summary>
/// Режим отрисовки собственной рамки окна приложения.
///
/// Там, где MarkMello подменяет системное оформление своим, окно остаётся без
/// видимого контура, и на светлой теме два перекрывающихся окна сливаются в
/// одно полотно — становится непонятно, где заканчивается один документ и
/// начинается другой.
/// </summary>
public enum WindowBorderMode
{
    /// <summary>
    /// Рисовать рамку там, где приложение само отвечает за оформление окна, и
    /// не рисовать там, где контур рисует система.
    /// </summary>
    Auto = 0,

    /// <summary>Всегда рисовать рамку.</summary>
    On = 1,

    /// <summary>Никогда не рисовать рамку.</summary>
    Off = 2
}
